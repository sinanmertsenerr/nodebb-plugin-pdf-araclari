export const uiLangOf = lang => (/^tr/i.test(String(lang || '')) ? 'tr' : 'en');

export function makeT(lang) {
	const dict = UI[uiLangOf(lang)];
	return (key, ...args) => String(dict[key] !== undefined ? dict[key] : (UI.tr[key] !== undefined ? UI.tr[key] : key))
		.replace(/%(\d)/g, (m, i) => (args[i - 1] !== undefined ? args[i - 1] : ''));
}
